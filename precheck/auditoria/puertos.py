"""Puertos del núcleo (contracts/public-api.md §Puertos)."""
from typing import Iterator, Mapping, Optional, Protocol, Sequence, runtime_checkable

from precheck.auditoria.cadena import EventoNuevo, EventoRegistrado


@runtime_checkable
class RepositorioBitacora(Protocol):
    def anexar(self, cadena_id: str, evento: EventoNuevo, usos: Sequence[tuple] = (),
               contenidos: Sequence[Mapping] = (), cabezas: Optional[Mapping[str, int]] = None
               ) -> EventoRegistrado: ...
    def anexar_lote(self, cadena_id: str, eventos: Sequence[EventoNuevo]) -> list[EventoRegistrado]: ...
    def leer(self, cadena_id: str, desde: int = 1) -> Iterator[EventoRegistrado]: ...
    def evento(self, cadena_id: str, seq: int) -> Optional[EventoRegistrado]: ...
    def cadenas(self) -> list[str]: ...
    def cabezas(self) -> dict: ...
    def guardar_contenido(self, contenido: Mapping) -> str: ...
    def contenido(self, hash_: str) -> Mapping: ...
    def usos(self, regla_id: str, version: int) -> list: ...


@runtime_checkable
class DestinoAnclaje(Protocol):
    def exportar(self, sello) -> str: ...
    def ultimo(self) -> Optional[object]: ...
